//! Urushi's client/daemon wire protocol.
//!
//! - [`v1`]: types generated from `proto/urushi/v1/*.proto`. The schema is the source of truth.
//! - [`codec`]: length-prefixed framing. With the `io` feature it also offers async
//!   helpers over tokio streams.
//! - [`convert`]: lossless conversions between wire types and `urushi-core` domain types.
//! - [`envelope`]: small constructors for building envelopes without boilerplate.
//!
//! The evolution rules are in `docs/protocol.md` and the `change-protocol` skill.

pub mod codec;
pub mod convert;
pub mod envelope;

/// Generated protobuf types for protocol v1.
#[allow(
    missing_docs,
    unreachable_pub,
    clippy::all,
    clippy::pedantic,
    reason = "generated by prost; documented in the .proto files"
)]
pub mod v1 {
    include!(concat!(env!("OUT_DIR"), "/urushi.v1.rs"));
}

/// Major protocol version. Clients with a different major version are rejected.
pub const PROTOCOL_MAJOR: u32 = 1;
/// Minor protocol version. Increases with each additive change that clients may detect.
pub const PROTOCOL_MINOR: u32 = 0;
